// Generates the land outline for the About page footprints map from
// Natural Earth (public domain). Run once; the output is committed.
// To cover a new area, edit BOUNDS or COUNTRIES below and re-run.
import { writeFile } from "node:fs/promises";
import path from "node:path";

const SOURCE =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson";
const OUTPUT = path.resolve(
  import.meta.dirname,
  "../src/app/about/_components/footprints-map-data.ts",
);

const COUNTRIES = ["IDN", "SGP"];
// Drawn faintly so neighbouring land doesn't read as Indonesia.
const CONTEXT_COUNTRIES = ["MYS"];
const BOUNDS = { west: 94.5, east: 141.5, north: 6.5, south: -11.5 };
const WIDTH = 1000;

const scale = WIDTH / (BOUNDS.east - BOUNDS.west);
const height = Math.round((BOUNDS.north - BOUNDS.south) * scale);

function project([lng, lat]) {
  return [
    Math.round((lng - BOUNDS.west) * scale * 10) / 10,
    Math.round((BOUNDS.north - lat) * scale * 10) / 10,
  ];
}

function ringToPath(ring) {
  const points = [];
  for (const coordinate of ring) {
    const [x, y] = project(coordinate);
    const last = points.at(-1);
    if (!last || last[0] !== x || last[1] !== y) points.push([x, y]);
  }
  if (points.length < 3) return "";
  return `M${points.map(([x, y]) => `${x} ${y}`).join("L")}Z`;
}

function featureToPath({ geometry }) {
  const polygons =
    geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  return polygons.flat().map(ringToPath).join("");
}

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`Failed to fetch Natural Earth data: ${response.status}`);
}
const { features } = await response.json();

function countryPaths(codes) {
  const paths = features
    .filter((feature) => codes.includes(feature.properties.ADM0_A3))
    .map(featureToPath);
  if (paths.length !== codes.length) {
    throw new Error(`Expected ${codes.length} countries, got ${paths.length}`);
  }
  return paths;
}

const landPaths = countryPaths(COUNTRIES);
const contextPaths = countryPaths(CONTEXT_COUNTRIES);

await writeFile(
  OUTPUT,
  `// Generated by scripts/generate-footprints-map.mjs. Do not edit by hand.
// Land outlines from Natural Earth (public domain), equirectangular projection.

export const MAP_BOUNDS = ${JSON.stringify(BOUNDS)};
export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${height};

export const landPaths = ${JSON.stringify(landPaths)};

export const contextPaths = ${JSON.stringify(contextPaths)};
`,
);
console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}`);
